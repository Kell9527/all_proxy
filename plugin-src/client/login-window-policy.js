/**
 * 登录窗口的打开策略（纯函数）。
 *
 * ## 为什么 OfficeAce 不自动开窗（用户 2026-10-14 报障）
 *
 * 「OfficeAce 新建账号每次都会自动登录同一个账号」—— 根因是华为云授权页
 * （`auth.huaweicloud.com/authui/login.html`）是 **SSO 页面**：浏览器里
 * 已登录的华为账号会被**静默复用**，授权瞬间完成，用户连「选账号」的界面
 * 都看不到。自动 `window.open` 等于**替用户决定了用哪个账号**。
 *
 * 来源仓库的解法是宿主 spawn **无痕浏览器窗口**（`openIncognitoWindow`，
 * 华为 authui 静默复用会话 ⇒ 换账号必须无痕）。但 all_proxy 是 Web 服务：
 * 进程可能跑在远程/无 GUI 的机器上，spawn 的是**服务端**的浏览器，用户
 * 根本看不见 —— 那条路在这里不可行。
 *
 * 故本项目的取舍：**不自动开窗，把链接交给用户**。用户想用哪个浏览器、
 * 要不要无痕，自己决定（提示文案里讲清「静默复用」这件事）。授权在任意
 * 机器上完成都会落账号（code 由服务端轮询获取，与 Accio 的 loopback 不同，
 * OfficeAce 的链接跨机器打开也能用）。
 *
 * ## ⚠️⚠️ 为什么 Magicrew **更加**不能自动开窗（2026-10-30 用户报障）
 *
 * 用户原话：「我点进去链接后 https://www.letsmagic.cn/login 也没有响应回来，
 * 而且这种情况在同个浏览器，只能一个账号」。**两个症状同一个根因**：
 *
 * magicrew 没有 OAuth 回调，凭据只存在于**服务端那次登录所开的那个浏览器**的
 * localStorage 里 —— 服务端读的是 `mkdtempSync` 出来的**一次性 profile**。
 * 而 `loginUrl` 在其余 provider 的语义是「用户在自己浏览器里打开、授权回调回来」，
 * 对 magicrew **完全不成立**：用户在**自己的**浏览器里登录，服务端那扇窗是空的，
 * 永远等不到凭据 ⇒ 界面上就是「点了链接没有任何反应」，直到 4 分钟超时。
 *
 * 「只能一个账号」是同一件事的另一面：**一个浏览器 profile 的 localStorage
 * 只存得下一份 jwt**。用户在同一个浏览器里登第二个账号，等于把第一份覆盖掉，
 * 而服务端读的还是它那扇一次性窗口 —— 两份都读不到。
 *
 * ⇒ 与 OfficeAce 同样**不自动开窗**，但**理由不同、提示也不同**：
 * magicrew 的登录窗口是**服务端**已经弹出的那个，用户要去看**服务端**的屏幕；
 * 链接只对「服务端无桌面」的场景有意义，且那时它不叫「授权链接」，
 * 而是「在你本机浏览器登录后，用『从本机浏览器导入』把凭据读回去」。
 *
 * 其余 provider 保持自动开窗：它们的授权页要么要求显式操作（账号密码/
 * 验证码/扫码），要么复用同一账号是用户可预期的，自动开窗省一次点击。
 */

/**
 * 该 provider 的「+ 新建账号」是否自动打开授权页窗口。
 *
 * @returns `false` 对 **OfficeAce**（SSO 静默复用）与 **Magicrew**（凭据在服务端
 *   那扇一次性 profile 的窗口里，链接给用户打开毫无意义）。理由见文件头。
 */
export function shouldAutoOpenLoginWindow(provider) {
  if (provider === 'officeace') return false;
  // ⚠️ magicrew **也**返回 false，但**不是**因为 SSO：它的登录窗口由**服务端**
  //    已经 spawn 出来了（见 `magicrew-browser-login.ts`）。在前端再开一个
  //    只会在用户自己的浏览器里登一个服务端读不到的地方 —— 用户看到的就是
  //    「点了链接没有任何反应」。
  if (provider === 'magicrew') return false;
  return true;
}

/**
 * 登录链接区域的提示文案（按 provider 的授权页特性）。
 *
 * ⚠️ OfficeAce 的文案必须讲清三件事（用户 2026-10-14 连续踩坑）：
 * 1. **授权页不提供「选账号」**——它直接用浏览器里已登录的华为账号授权，
 *    所以要加新账号必须在无痕窗口里登一个**不同的华为账号**；登同一个账号
 *    授权出来的还是已加过的那一个（判重会提示「已在池中」）。
 * 2. 看到华为云的「欢迎使用OfficeAce，请返回客户端体验」**即授权成功**，
 *    那是华为云的回调页，不是错误——回到本页看账号列表即可。
 * 3. 复制到无痕窗口/其他浏览器打开（在当前浏览器打开会直接登同一个账号）。
 */
export function loginLinkHint(provider) {
  if (provider === 'officeace') {
    return '请复制下方链接，在**无痕窗口或其他浏览器**中打开完成华为云授权。'
      + '⚠️ 授权页不能选账号——它直接用浏览器里已登录的华为账号授权，'
      + '所以要添加**新账号**，必须在无痕窗口里登录一个**不同的华为账号**；'
      + '登录同一个账号授权出来的仍是已加过的那一个（会提示「已在池中」）。'
      + '看到「欢迎使用OfficeAce，请返回客户端体验」即表示授权成功，'
      + '回到本页查看账号列表即可。';
  }
  /**
   * ⚠️⚠️ Magicrew 的文案必须讲清「窗口在**服务端**」，这是用户 2026-10-30 报障的
   * 直接教训（「我点进去链接后 …/login 也没有响应回来」—— 他把链接当成了授权入口，
   * 而在**他自己**浏览器里登录，服务端那次一次性 profile 里永远是空的）。
   *
   * 四件事缺一不可：
   * 1. **登录窗口已经自动打开在服务端**（不是这里、不是点链接）；
   * 2. 服务端跑在远程/容器里时**看不到那个窗口** ⇒ 改用「从本机浏览器导入」；
   * 3. **加新账号要开无痕窗口** —— 一个 profile 的 localStorage 只存一份 jwt，
   *    在同一个浏览器里登第二个账号会把第一个**覆盖**掉（用户原话「同个浏览器只能
   *    一个账号」正是这个）；
   * 4. 不要指望这里的链接能「授权回调」—— 它没有回调，凭据靠**读浏览器**。
   */
  if (provider === 'magicrew') {
    // ⚠️ 两条腿的**适用条件互斥**，必须都说清楚：
    //    · 服务端开窗（主按钮）：要求服务端**有桌面**，能看到弹出的浏览器窗口；
    //    · 从本机浏览器导入（次按钮）：要求**运行本服务那台机器**的浏览器里
    //      已经登录过 www.letsmagic.cn。
    // 用户 2026-10-30 两条都踩过：先点链接（没反应），再点导入（读不到，
    // 因为那台机器的浏览器确实没登过）。
    return '登录窗口已由**服务端**自动打开（不是你当前这个浏览器）—— '
      + '请在**运行本服务的那台机器**上完成登录，凭据会被自动读回。'
      + '⚠️ 若本服务跑在远程/容器/无桌面环境：你在那边看不到窗口，'
      + '请改在本机浏览器登录 www.letsmagic.cn，再点「从本机浏览器导入」。'
      + '⚠️ 要添加**新账号**：换一个浏览器或无痕窗口各登一次再各导入一次'
      + '（一个浏览器只能存一份登录态，同一窗口登第二个会覆盖第一个）。';
  }
  return '请在弹出的窗口中完成登录；若窗口被浏览器拦截、或你在远程管理本服务，'
    + '点下方链接在**本机浏览器**打开。授权完成后账号自动加入账号池，'
    + '可重复「+ 新建账号」登录多个账号。';
}
