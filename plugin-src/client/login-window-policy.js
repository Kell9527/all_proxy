/**
 * 登录窗口的打开策略（纯函数）。
 *
 * ## 为什么 OfficeAce 不自动开窗（用户 2026-10-14 报障）
 *
 * 「OfficeAce 新建账号每次都会自动登录同一个账号」—— 根因是华为云授权页
 * （`auth.huaweicloud.com/authui/login.html`）是 **SSO 页面**：浏览器里
 * 已登录的华为账号会被**静默复用**，授权瞬间完成，用户连「选账号」的界面
 * 都看不到。自动 `window.open` 等于**替用户决定了用哪个账号**。
 *
 * 来源仓库的解法是宿主 spawn **无痕浏览器窗口**（`openIncognitoWindow`，
 * 华为 authui 静默复用会话 ⇒ 换账号必须无痕）。但 all_proxy 是 Web 服务：
 * 进程可能跑在远程/无 GUI 的机器上，spawn 的是**服务端**的浏览器，用户
 * 根本看不见 —— 那条路在这里不可行。
 *
 * 故本项目的取舍：**不自动开窗，把链接交给用户**。用户想用哪个浏览器、
 * 要不要无痕，自己决定（提示文案里讲清「静默复用」这件事）。授权在任意
 * 机器上完成都会落账号（code 由服务端轮询获取，与 Accio 的 loopback 不同，
 * OfficeAce 的链接跨机器打开也能用）。
 *
 * 其余 provider 保持自动开窗：它们的授权页要么要求显式操作（账号密码/
 * 验证码/扫码），要么复用同一账号是用户可预期的，自动开窗省一次点击。
 */

/**
 * 该 provider 的「+ 新建账号」是否自动打开授权页窗口。
 *
 * @returns `false` 仅对 OfficeAce（SSO 静默复用，见文件头）。
 */
export function shouldAutoOpenLoginWindow(provider) {
  return provider !== 'officeace';
}

/**
 * 登录链接区域的提示文案（按 provider 的授权页特性）。
 *
 * ⚠️ OfficeAce 的文案必须点明「静默复用」与「无痕窗口」—— 不说的话用户
 * 照着链接在当前浏览器点下去，登的还是同一个账号，然后回来报障「换了
 * 账号还是老的」。
 */
export function loginLinkHint(provider) {
  if (provider === 'officeace') {
    return '请复制下方链接，在**无痕窗口或其他浏览器**中打开完成华为云授权'
      + '（授权页会复用浏览器里已登录的账号，不重新询问；在当前浏览器打开会直接登同一个账号）。'
      + '授权完成后账号自动加入账号池，可重复「+ 新建账号」添加多个账号。';
  }
  return '请在弹出的窗口中完成登录；若窗口被浏览器拦截、或你在远程管理本服务，'
    + '点下方链接在**本机浏览器**打开。授权完成后账号自动加入账号池，'
    + '可重复「+ 新建账号」登录多个账号。';
}
